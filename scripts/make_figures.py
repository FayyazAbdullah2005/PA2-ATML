"""Build the report figures from the saved result JSONs.

Usage:
    python -m scripts.make_figures            # every figure whose inputs exist
    python -m scripts.make_figures --list

Reads only results/**/*.json produced by the task scripts; missing inputs are skipped so
this can be run while experiments are still in flight. Matplotlib uses the Agg backend, so
it never touches the GPU.
"""

from __future__ import annotations

import argparse
import json
import re

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from common.data import repo_path  # noqa: E402

RESULTS = repo_path("results")
FIGURES = repo_path("figures")


def load(relative: str):
    path = RESULTS.parent / relative
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:
        return None


def save(fig, name: str) -> None:
    FIGURES.mkdir(parents=True, exist_ok=True)
    path = FIGURES / f"{name}.png"
    fig.savefig(path, dpi=160, bbox_inches="tight")
    print(f"wrote {path}")

    # report/main.tex includes figures as figures/taskN/<name>.png, so mirror the flat file
    # into that layout too. Both copies are kept: the flat one for inspection, the nested one
    # for the report, and neither has to be regenerated by hand after a rebuild.
    m = re.match(r"^task(\d+)_(.+)$", name)
    if m:
        nested = FIGURES / f"task{m.group(1)}" / f"{m.group(2)}.png"
        nested.parent.mkdir(parents=True, exist_ok=True)
        fig.savefig(nested, dpi=160, bbox_inches="tight")
        print(f"wrote {nested}")

    plt.close(fig)


def panel(ax, series, title, ylabel):
    for label, xs, ys in series:
        ax.plot(xs, ys, marker="o", markersize=3, label=label)
    ax.set_title(title, fontsize=10)
    ax.set_xlabel("update", fontsize=8)
    ax.set_ylabel(ylabel, fontsize=8)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7)
    ax.tick_params(labelsize=7)


# --------------------------------------------------------------------------- Task 1
def figure_task1():
    ablation = load("results/task1_dpo/beta_ablation.json")
    if ablation:
        rows = sorted(ablation["results"], key=lambda r: r["beta"])
        betas = [r["beta"] for r in rows]
        fig, axes = plt.subplots(2, 2, figsize=(7, 5))
        for ax, key, label in [
            (axes[0][0], "heldout_preference_accuracy", "held-out preference accuracy"),
            (axes[0][1], "kl_token_mean", "KL from reference (token mean)"),
            (axes[1][0], "reward_model_mean", "reward-model score"),
            (axes[1][1], "response_length_mean", "response length (tokens)"),
        ]:
            ax.plot(betas, [r[key] for r in rows], marker="o")
            ax.set_title(f"DPO vs beta: {label}", fontsize=10)
            ax.set_xlabel("beta", fontsize=8)
            ax.tick_params(labelsize=7)
            ax.grid(alpha=0.3)
        fig.suptitle("Task 1: regularization strength (short forks, identical budget)", fontsize=11)
        save(fig, "task1_beta_ablation")

    length = load("results/task1_dpo/length_confounding.json")
    if length:
        strata = length["strata"]
        names = list(length["conditions"].keys())
        fig, axes = plt.subplots(1, 2, figsize=(7, 3))
        width = 0.35
        for i, name in enumerate(names):
            vals = [length["conditions"][name]["by_stratum"][s]["preference_accuracy"] for s in strata]
            axes[0].bar([x + i * width for x in range(len(strata))], vals, width, label=name)
        axes[0].set_xticks([x + width / 2 for x in range(len(strata))])
        axes[0].set_xticklabels([s.replace("_", "\n") for s in strata], fontsize=8)
        axes[0].set_ylabel("preference accuracy", fontsize=8)
        axes[0].set_title("Accuracy by length stratum", fontsize=10)
        axes[0].legend(fontsize=7)
        axes[0].grid(alpha=0.3, axis="y")

        names2 = names
        gen = [length["conditions"][n]["generated_length"]["mean"] for n in names2]
        comp = [length["conditions"][n]["word_limit_compliance"] or 0.0 for n in names2]
        axes[1].bar(names2, gen, color="tab:blue", alpha=0.7, label="mean tokens")
        axes[1].set_ylabel("mean response tokens", fontsize=8)
        twin = axes[1].twinx()
        twin.plot(names2, comp, color="tab:red", marker="o", label="word-limit compliance")
        twin.set_ylabel("word-limit compliance", fontsize=8)
        axes[1].set_title("Generated length and instruction compliance", fontsize=10)
        axes[1].tick_params(labelsize=7)
        twin.tick_params(labelsize=7)
        save(fig, "task1_length_confounding")

    train_log = repo_path("results/task1_dpo/standard_train_log.jsonl")
    if train_log.exists():
        rows = [json.loads(l) for l in train_log.read_text(encoding="utf-8").splitlines() if l.strip()]
        fig, ax = plt.subplots(figsize=(4.5, 3))
        panel(ax, [("loss", [r["step"] for r in rows], [r["loss"] for r in rows])],
              "Standard DPO training", "loss")
        save(fig, "task1_dpo_training")


# --------------------------------------------------------------------------- Task 2
def figure_task2():
    log = repo_path("results/task2_ppo/standard_updates.jsonl")
    if log.exists():
        rows = [json.loads(l) for l in log.read_text(encoding="utf-8").splitlines() if l.strip()]
        xs = [r["update"] for r in rows]
        fig, axes = plt.subplots(2, 3, figsize=(10, 6.2))
        panel(axes[0][0], [("reward", xs, [r["learned_reward_mean"] for r in rows])], "Learned reward", "reward")
        panel(axes[0][1], [("KL", xs, [r["kl_token_mean"] for r in rows])], "KL from reference", "KL (token mean)")
        panel(axes[0][2], [("pi", xs, [r["policy_loss"] for r in rows]),
                           ("v", xs, [r["value_loss"] for r in rows])], "Losses", "loss")
        panel(axes[1][0], [("entropy", xs, [r["entropy_token_mean"] for r in rows])], "Entropy", "nats/token")
        panel(axes[1][1], [("clip", xs, [r["clip_fraction"] for r in rows])], "Clip fraction", "fraction")
        panel(axes[1][2], [("len", xs, [r["response_length_mean"] for r in rows])], "Response length", "tokens")
        fig.suptitle("Task 2: standard 20-update PPO continuation", fontsize=11, y=0.98)
        fig.tight_layout(rect=[0, 0.02, 1, 0.96], h_pad=2.5, w_pad=2.0)
        save(fig, "task2_ppo_continuation")

    clipping = load("results/task2_ppo/clipping_study.json")
    if clipping:
        geo = sorted(clipping["cache_geometry"], key=lambda g: g["epsilon"])
        fig, axes = plt.subplots(1, 2, figsize=(7, 3))
        axes[0].plot([g["epsilon"] for g in geo], [g["affected_token_fraction"] for g in geo], marker="o")
        axes[0].set_xlabel("epsilon", fontsize=8)
        axes[0].set_ylabel("affected-token fraction", fontsize=8)
        axes[0].set_title("Cached rollout batch", fontsize=10)
        axes[0].grid(alpha=0.3)
        forks = clipping.get("forks", [])
        if forks:
            forks = sorted(forks, key=lambda f: f["clip_epsilon"])
            labels = [f"{f['clip_epsilon']:g}" for f in forks]
            axes[1].bar(labels, [f["heldout"]["reward_model_mean"] for f in forks], color="tab:blue", alpha=0.7)
            axes[1].set_xlabel("epsilon", fontsize=8)
            axes[1].set_ylabel("held-out reward", fontsize=8)
            twin = axes[1].twinx()
            twin.plot(labels, [f["heldout"]["kl_token_mean"] for f in forks], color="tab:red", marker="o")
            twin.set_ylabel("held-out KL", fontsize=8)
            axes[1].set_title("Matched 8-update forks", fontsize=10)
        save(fig, "task2_clipping")

    kl = load("results/task2_ppo/kl_ablation.json")
    if kl:
        rows = sorted(kl["results"], key=lambda r: r["kl_beta"])
        labels = [f"{r['kl_beta']:g}" for r in rows]
        fig, axes = plt.subplots(1, 3, figsize=(9, 3))
        for ax, key, title in [
            (axes[0], "reward_model_mean", "Held-out reward"),
            (axes[1], "kl_token_mean", "Held-out KL from reference"),
            (axes[2], "response_length_mean", "Response length"),
        ]:
            ax.bar(labels, [r["heldout"][key] for r in rows], color="tab:blue", alpha=0.7)
            ax.set_xlabel("beta_KL", fontsize=8)
            ax.set_title(title, fontsize=10)
            ax.tick_params(labelsize=7)
            ax.grid(alpha=0.3, axis="y")
        save(fig, "task2_kl_pressure")


