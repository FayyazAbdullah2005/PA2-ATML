def figure_task5():
    dom = load("results/task5_feedback/gsm_eval.json")
    transfer = load("results/task5_feedback/transfer_eval.json")
    if dom:
        policies = list(dom["policies"].keys())
        fig, axes = plt.subplots(1, 2, figsize=(7, 3))
        axes[0].bar(policies, [dom["policies"][p]["exact_accuracy"] for p in policies],
                    color="tab:blue", alpha=0.8, label="GSM8K (in-domain)")
        if transfer:
            axes[0].bar(policies, [transfer["policies"][p]["exact_accuracy"] for p in policies if p in transfer["policies"]],
                        color="tab:orange", alpha=0.6, label="SVAMP (transfer)")
            axes[0].legend(fontsize=7)
        axes[0].set_ylabel("exact answer accuracy", fontsize=8)
        axes[0].set_title("RLVR vs RLAIF", fontsize=10)
        axes[0].tick_params(labelsize=8)
        axes[0].grid(alpha=0.3, axis="y")

        win = [dom["policies"][p].get("pairwise_vs_sft", {}).get("win_rate") for p in policies]
        win = [w for w in win if w is not None]
        if win:
            axes[1].bar([p for p in policies if dom["policies"][p].get("pairwise_vs_sft")], win,
                        color="tab:green", alpha=0.8)
        axes[1].axhline(0.5, color="grey", linestyle="--", linewidth=1)
        axes[1].set_ylabel("AI pairwise win rate vs SFT", fontsize=8)
        axes[1].set_title("Judge preference (in-domain)", fontsize=10)
        axes[1].tick_params(labelsize=8)
        axes[1].grid(alpha=0.3, axis="y")
        save(fig, "task5_rlvr_vs_rlaif")

    diag = load("results/task5_feedback/perturbation_study.json")
    if diag:
        variants = list(diag["by_variant"].keys())
        labels = [v.replace("_", "\n") for v in variants]
        fig, ax = plt.subplots(figsize=(8, 3.4))
        width = 0.2
        for i, (mechanism, color) in enumerate([("rlvr", "tab:blue"), ("rlaif", "tab:orange")]):
            for j, outcome in enumerate(["better", "tie", "wrong"]):
                ax.bar([x + (i * 3 + j) * width for x in range(len(variants))],
                       [diag["by_variant"][v][mechanism][outcome] for v in variants],
                       width, color=color, alpha=0.5 + 0.25 * j, label=f"{mechanism}: {outcome}")
        ax.set_xticks([x + 1.5 * width for x in range(len(variants))])
        ax.set_xticklabels(labels, fontsize=7)
        ax.set_ylabel("fraction of controlled pairs", fontsize=8)
        ax.set_title("Controlled reward diagnostics", fontsize=10)
        ax.legend(fontsize=7, ncol=3)
        save(fig, "task5_perturbations")


FIGURES_TO_BUILD = {
    "task1_beta_ablation": figure_task1,
    "task2_ppo_continuation": figure_task2,
    "task3_grpo_continuation": figure_task3,
    "task4_safety_calibration": figure_task4,
    "task5_rlvr_vs_rlaif": figure_task5,
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true")
    args = ap.parse_args()
    if args.list:
        for name in FIGURES_TO_BUILD:
            print(name)
        return
    for name, builder in FIGURES_TO_BUILD.items():
        try:
            builder()
        except Exception as exc:  # a missing input should never stop the rest
            print(f"[skip] {name}: {exc}")
    print(f"figures -> {FIGURES}")


if __name__ == "__main__":
    main()