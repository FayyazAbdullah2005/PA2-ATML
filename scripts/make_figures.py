def figure_task4():
    safety = load("results/task4_safety/safety_metrics.json")
    if not safety:
        return
    policies = list(safety["policies"].keys())
    metrics = [
        ("safe_answer_rate", "safe-answer rate"),
        ("safe_over_refusal_rate", "safe over-refusal"),
        ("unsafe_compliance_rate", "unsafe compliance"),
        ("unsafe_justified_refusal_rate", "justified refusal"),
        ("ambiguous_rate", "ambiguous"),
    ]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.2))
    width = 0.16
    for i, (key, label) in enumerate(metrics):
        axes[0].bar([x + i * width for x in range(len(policies))],
                    [safety["policies"][p][key] or 0.0 for p in policies], width, label=label)
    axes[0].set_xticks([x + 2 * width for x in range(len(policies))])
    axes[0].set_xticklabels(policies, fontsize=8)
    axes[0].set_ylabel("rate", fontsize=8)
    axes[0].set_title("Safety calibration", fontsize=10)
    axes[0].legend(fontsize=6.5, ncol=2)
    axes[0].grid(alpha=0.3, axis="y")

    axes[1].bar(policies, [safety["policies"][p]["mean_response_tokens"] for p in policies],
                color="tab:blue", alpha=0.7)
    axes[1].set_ylabel("mean response tokens", fontsize=8)
    axes[1].set_title("Response length", fontsize=10)
    axes[1].tick_params(labelsize=8)
    axes[1].grid(alpha=0.3, axis="y")
    save(fig, "task4_safety_calibration")

    categories = sorted(safety["policies"][policies[0]]["by_category"].keys())
    labels = ["SAFE_ANSWER", "OVER_REFUSAL", "JUSTIFIED_REFUSAL", "UNSAFE_COMPLIANCE", "AMBIGUOUS"]
    fig, ax = plt.subplots(figsize=(8, 3.2))
    bottom = [0.0] * len(categories)
    for label in labels:
        row = [
            sum(safety["policies"][p]["by_category"][c]["label_fractions"].get(label, 0.0) for p in policies) / len(policies)
            for c in categories
        ]
        ax.bar(categories, row, bottom=bottom, label=label, alpha=0.85)
        bottom = [b + r for b, r in zip(bottom, row)]
    ax.set_ylabel("mean judge-label fraction", fontsize=8)
    ax.set_title("Judge-label distribution across XSTest categories", fontsize=10)
    ax.tick_params(labelsize=7, axis="x")
    plt.setp(ax.get_xticklabels(), rotation=30, ha="right")
    ax.legend(fontsize=7)
    save(fig, "task4_category_breakdown")


